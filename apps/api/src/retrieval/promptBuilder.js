export function buildPrompt(context, question) {
  return `
आप एक ज्ञान सहायक हैं।

नियम:
- केवल नीचे दिए गए संदर्भ के आधार पर उत्तर दें।
- यदि उत्तर संदर्भ में उपलब्ध नहीं है, तो साफ़ लिखें:
  "दिए गए दस्तावेज़ों के आधार पर जानकारी उपलब्ध नहीं है।"
- उत्तर हिंदी में दें।
- उत्तर संक्षिप्त और स्पष्ट दें।
- अनावश्यक दोहराव न करें।


संदर्भ:
${context}

प्रश्न:
${question}

उत्तर:
`.trim();
}
